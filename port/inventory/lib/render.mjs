// docs/parity.md and the Phase 2 block in docs/port-notes.md.
import { AREAS, STATUSES } from './features.mjs';
import { CATEGORIES, TERMS } from './branding.mjs';

export const PHASE2_START = '<!-- phase2:start -->';
export const PHASE2_END = '<!-- phase2:end -->';
const PHASE1_END = '<!-- phase1:end -->';
const MAX_ROWS = 100;

/** @param {unknown} v */
function cell(v) {
  return String(v ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

/** @param {string} p */
function basename(p) {
  return p.slice(p.lastIndexOf('/') + 1);
}

/**
 * Markdown table. Over 100 rows, the first 100 by weight descending plus a note.
 * @param {string[]} headers
 * @param {{ cells: unknown[], weight?: number }[]} rows
 * @param {string} jsonFile
 * @returns {string[]}
 */
function table(headers, rows, jsonFile) {
  if (rows.length === 0) return ['- none'];
  let shown = rows;
  if (rows.length > MAX_ROWS) {
    shown = rows
      .map((r, i) => ({ r, i }))
      .sort((a, b) => (b.r.weight ?? 0) - (a.r.weight ?? 0) || a.i - b.i)
      .slice(0, MAX_ROWS)
      .map(x => x.r);
  }
  const lines = [
    `| ${headers.join(' | ')} |`,
    `|${headers.map(() => '---').join('|')}|`,
    ...shown.map(r => `| ${r.cells.map(cell).join(' | ')} |`),
  ];
  if (rows.length > MAX_ROWS) {
    lines.push('', `Plus ${rows.length - MAX_ROWS} more in ${jsonFile}.`);
  }
  return lines;
}

/**
 * @param {string[]} items
 * @param {string} jsonFile
 * @returns {string[]}
 */
function bullets(items, jsonFile) {
  if (items.length === 0) return ['- none'];
  const shown = items.slice(0, MAX_ROWS).map(i => `- ${i}`);
  if (items.length > MAX_ROWS) shown.push('', `Plus ${items.length - MAX_ROWS} more in ${jsonFile}.`);
  return shown;
}

/**
 * @param {any} parity
 * @param {any} featuresFile
 * @returns {string}
 */
export function renderParityMd(parity, featuresFile) {
  /** @type {Map<string, any>} */
  const info = new Map(parity.features.map((/** @type {any} */ f) => [f.id, f]));
  /** @type {string[]} */
  const out = [];
  out.push('# Parity checklist', '');
  out.push(
    'Generated from `port/features.json` and `port/state/inventory/`. Edit `port/features.json`, then run `port/inventory.sh render`. Do not edit this file by hand.',
    '',
  );
  out.push('| Status | Features |', '|---|---|');
  for (const s of STATUSES) {
    const row = parity.totals.byStatus.find((/** @type {any} */ b) => b.status === s);
    out.push(`| ${s} | ${row ? row.count : 0} |`);
  }
  out.push('');

  for (const area of AREAS) {
    const feats = featuresFile.features
      .filter((/** @type {any} */ f) => f.area === area)
      .sort((/** @type {any} */ a, /** @type {any} */ b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
    if (feats.length === 0) continue;
    out.push(`## ${area}`, '');
    out.push('| Feature | Visibility | Status | Entry points | Data layer | Tests (unit / int / e2e) |');
    out.push('|---|---|---|---|---|---|');
    for (const f of feats) {
      const p = info.get(f.id);
      const dl = p ? p.dataLayer.map((/** @type {any} */ d) => basename(d.path)) : [];
      const shown = dl.slice(0, 5);
      let dlText = shown.join(', ');
      if (dl.length > 5) dlText += `, +${dl.length - 5}`;
      if (!dlText) dlText = '-';
      const t = p ? p.tests : { unit: [], int: [], e2e: [] };
      out.push(
        `| ${cell(f.name)} (\`${f.id}\`) | ${f.visibility} | ${f.status} | ${f.entryPoints.length} | ${cell(dlText)} | ${t.unit.length} / ${t.int.length} / ${t.e2e.length} |`,
      );
    }
    out.push('');
    for (const f of feats) {
      const p = info.get(f.id);
      out.push(`### ${f.name} (\`${f.id}\`)`, '', f.description, '', 'Entry points:', '');
      const eps = p ? p.entryPoints : f.entryPoints.map((/** @type {string} */ id) => ({ id, file: '' }));
      for (const ep of eps) out.push(`- \`${ep.id}\`, \`${ep.file}\``);
      out.push('');
      if (f.decision) {
        const note = String(f.decision.note ?? '').trim();
        const sentence = /[.!?]$/.test(note) ? note : `${note}.`;
        const signed = f.decision.signedOffBy
          ? `Signed off by ${f.decision.signedOffBy} on ${f.decision.date}.`
          : 'Not signed off.';
        out.push(`Decision: ${sentence} ${signed}`, '');
      }
    }
  }
  return out.join('\n').replace(/\n+$/, '') + '\n';
}

/**
 * @param {any} all
 * @returns {string}
 */
export function renderNotesBlock(all) {
  /** @type {string[]} */
  const out = [];
  const sha = String(all.importCommit ?? '').slice(0, 12);
  out.push(PHASE2_START, '## Phase 2: Inventory', '');
  out.push(`Inventory of commit ${sha}. Full detail is in \`port/state/inventory/\`.`, '');

  // Workspace map
  out.push('### Workspace map', '');
  out.push(
    ...table(
      ['Package', 'Directory', 'Role', 'Languages', 'Source files', 'Test files', 'CI targets'],
      all.workspaces.map((/** @type {any} */ w) => ({
        cells: [w.name, w.dir, w.role, w.languages.join(', '), w.sourceFiles, w.testFiles, w.ciTargets.join(', ')],
      })),
      'workspaces.json',
    ),
    '',
  );

  // Entry points
  out.push('### Entry points', '');
  const kinds = ['app_page', 'app_api_route', 'api_route', 'mcp_tool', 'task', 'cli_command', 'ingestion'];
  out.push(
    ...table(
      ['Kind', 'Count'],
      kinds.map(k => ({
        cells: [k, all.entryPoints.filter((/** @type {any} */ e) => e.kind === k).length],
      })),
      'entrypoints.json',
    ),
    '',
  );

  // Data layer
  out.push('### Data layer', '');
  out.push(
    ...table(
      ['Module', 'Reasons', 'Exports', 'Importers', 'Server-side'],
      all.dataLayer.map((/** @type {any} */ m) => ({
        cells: [`\`${m.path}\``, m.reasons.join(', '), m.exports.length, m.importers.length, m.serverSide ? 'yes' : 'no'],
        weight: m.importers.length,
      })),
      'datalayer.json',
    ),
    '',
  );

  // Server-side callers
  out.push('### Server-side data-store callers', '');
  const api = all.workspaces.find((/** @type {any} */ w) => w.role === 'API server and tasks');
  /** @type {Map<string, string[]>} */
  const callers = new Map();
  if (api) {
    for (const m of all.dataLayer) {
      for (const imp of m.importers) {
        if (imp.test || imp.workspace !== api.name) continue;
        const list = callers.get(imp.path) ?? [];
        list.push(m.path);
        callers.set(imp.path, list);
      }
    }
  }
  out.push(
    ...bullets(
      [...callers.keys()].sort().map(p => `\`${p}\`: ${/** @type {string[]} */ (callers.get(p)).map(x => `\`${x}\``).join(', ')}`),
      'datalayer.json',
    ),
    '',
  );

  // UI raw SQL
  out.push('### UI code with raw SQL or ClickHouse type names', '');
  out.push(
    ...table(
      ['File', 'SQL literals', 'Type names'],
      all.sql.appSites.map((/** @type {any} */ s) => ({
        cells: [`\`${s.path}\``, s.rawSql, s.typeNames],
        weight: s.rawSql + s.typeNames,
      })),
      'sql-catalog.json',
    ),
    '',
  );

  // Unmapped
  out.push('### ClickHouse constructs without a SQL++ mapping', '');
  out.push(
    ...table(
      ['Category', 'Name', 'Occurrences', 'Files'],
      all.sql.constructs
        .filter((/** @type {any} */ c) => c.classification === 'unmapped')
        .map((/** @type {any} */ c) => ({
          cells: [c.category, `\`${c.name}\``, c.occurrences, c.files.length],
          weight: c.occurrences,
        })),
      'sql-catalog.json',
    ),
    '',
  );

  // Mapped
  out.push('### Mapped constructs in use', '');
  out.push(
    ...table(
      ['Name', 'Occurrences', 'SQL++ approach'],
      all.sql.constructs
        .filter((/** @type {any} */ c) => c.classification === 'mapped')
        .map((/** @type {any} */ c) => ({
          cells: [`\`${c.name}\``, c.occurrences, c.sqlppApproach ?? ''],
          weight: c.occurrences,
        })),
      'sql-catalog.json',
    ),
    '',
  );

  // Schema
  out.push('### Schema', '');
  out.push(
    ...table(
      ['Table', 'Columns', 'Engine', 'Order by', 'TTL'],
      all.schema.tables.map((/** @type {any} */ t) => ({
        cells: [`\`${t.name}\``, t.columns.length, t.engine ?? '', t.orderBy ?? '', t.ttl ?? ''],
        weight: t.columns.length,
      })),
      'schema.json',
    ),
  );
  out.push('');
  if (all.schema.materializedViews.length === 0) out.push('Materialized views: none.');
  else {
    out.push('Materialized views:', '');
    for (const mv of all.schema.materializedViews) {
      out.push(`- \`${mv.name}\` → ${mv.target ? `\`${mv.target}\`` : 'none'}, from ${mv.sources.length ? mv.sources.map((/** @type {string} */ s) => `\`${s}\``).join(', ') : 'none'}.`);
    }
  }
  out.push('');

  // Ingestion
  out.push('### Ingestion', '');
  out.push('Collector components, pipelines, ClickHouse exporters, and management code.', '');
  const ing = all.ingestion;
  /** @type {string[]} */
  const ingLines = [];
  for (const b of ing.builderManifests) {
    /** @type {Map<string, number>} */
    const counts = new Map();
    for (const c of b.components) counts.set(c.section, (counts.get(c.section) ?? 0) + 1);
    ingLines.push(`Builder manifest \`${b.file}\`: ${[...counts].map(([s, n]) => `${n} ${s}`).join(', ') || 'no components'}.`);
  }
  for (const c of ing.collectorConfigs) {
    ingLines.push(
      `Collector config \`${c.file}\`: ${c.receivers.length} receivers, ${c.processors.length} processors, ${c.exporters.length} exporters; pipelines: ${c.pipelines.map((/** @type {any} */ p) => p.name).join(', ') || 'none'}.`,
    );
  }
  for (const e of ing.clickhouseExporters) ingLines.push(`ClickHouse component \`${e.name}\` in \`${e.file}\`.`);
  for (const g of ing.goSources.filter((/** @type {any} */ g) => g.clickhouseImports.length > 0)) {
    ingLines.push(`Go source \`${g.file}\` imports ${g.clickhouseImports.map((/** @type {string} */ i) => `\`${i}\``).join(', ')}.`);
  }
  for (const m of ing.managementCode) ingLines.push(`Management code \`${m}\`.`);
  out.push(...bullets(ingLines, 'ingestion.json'), '');

  // Integration test dependencies
  out.push('### Integration test dependencies', '');
  out.push(
    ...table(
      ['Workspace', 'Script', 'Command'],
      all.tests.integrationRequires.map((/** @type {any} */ r) => ({
        cells: [r.workspace, `\`${r.target}\``, `\`${r.command}\``],
      })),
      'tests.json',
    ),
    '',
  );

  // Branding
  out.push('### Branding', '');
  /** @type {Map<string, number>} */
  const bt = new Map();
  for (const t of all.branding.totals) bt.set(`${t.category}\0${t.term}`, t.count);
  out.push(
    ...table(
      ['Category', ...TERMS],
      CATEGORIES.map(c => ({ cells: [c, ...TERMS.map(t => bt.get(`${c}\0${t}`) ?? 0)] })),
      'branding.json',
    ),
    '',
  );

  // Parity (when features have been rendered)
  if (all.parity) {
    out.push('### Feature status', '');
    out.push(
      ...table(
        ['Status', 'Features'],
        all.parity.totals.byStatus.map((/** @type {any} */ b) => ({ cells: [b.status, b.count] })),
        'parity.json',
      ),
      '',
    );
  }

  // Plan corrections
  out.push('### Plan corrections', '');
  const corrections = [...all.planCheck.missingPaths, ...all.planCheck.missingSymbols].map(
    (/** @type {any} */ m) =>
      `\`${m.token}\` in ${m.document} line ${m.line}: not found. ${m.suggestion ? `Suggested: \`${m.suggestion}\`.` : 'No suggestion.'}`,
  );
  out.push(...bullets(corrections, 'plan-check.json'), '');

  // Warnings
  out.push('### Warnings', '');
  out.push(
    ...bullets(
      all.warnings.map((/** @type {any} */ w) => `${w.code}: ${w.count} occurrences. First: ${String(w.first).replace(/\r?\n/g, ' ')}`),
      'manifest.json',
    ),
  );
  out.push(PHASE2_END);
  return out.join('\n');
}

/**
 * Replace the text between markers (markers included in `block`), or insert the block
 * after the Phase 1 block, or at the end.
 * @param {string} fileText
 * @param {string} start
 * @param {string} end
 * @param {string} block
 * @returns {string}
 */
export function replaceBlock(fileText, start, end, block) {
  const s = fileText.indexOf(start);
  if (s >= 0) {
    const e = fileText.indexOf(end, s);
    if (e >= 0) return fileText.slice(0, s) + block + fileText.slice(e + end.length);
  }
  const p = fileText.indexOf(PHASE1_END);
  if (p >= 0) {
    const at = p + PHASE1_END.length;
    return fileText.slice(0, at) + '\n\n' + block + fileText.slice(at);
  }
  const base = fileText.replace(/\n*$/, '');
  return (base ? base + '\n\n' : '') + block + '\n';
}
