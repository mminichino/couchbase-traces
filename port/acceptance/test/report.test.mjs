import assert from 'node:assert/strict';
import { describe, it } from 'node:test';

import {
  computeReportStatus,
  renderAcceptanceMarkdown,
} from '../lib/report.mjs';

function check(id, status) {
  return {
    id,
    title: id,
    status,
    summary: status,
    details: null,
    evidence: [],
    durationMs: 0,
  };
}

describe('report status computation', () => {
  it('returns fail when any check failed', () => {
    assert.equal(
      computeReportStatus([check('A1', 'pass'), check('B1', 'fail'), check('K2', 'blocked')]),
      'fail',
    );
  });

  it('returns blocked when any blocked and none failed', () => {
    assert.equal(
      computeReportStatus([check('A1', 'pass'), check('K2', 'blocked')]),
      'blocked',
    );
  });

  it('returns pass when K2 passed and nothing failed/blocked', () => {
    assert.equal(
      computeReportStatus([check('A1', 'pass'), check('K2', 'pass')]),
      'pass',
    );
  });

  it('returns pass_local when all passed except K2 not pass', () => {
    assert.equal(
      computeReportStatus([check('A1', 'pass'), check('K2', 'skipped')]),
      'pass_local',
    );
  });

  it('returns pass_local when all passed and K2 absent', () => {
    assert.equal(computeReportStatus([check('A1', 'pass')]), 'pass_local');
  });
});

describe('docs/acceptance.md rendering', () => {
  it('renders a fixed report', () => {
    const report = {
      schemaVersion: 1,
      generatedAt: '2026-01-01T00:00:00.000Z',
      gitSha: 'abc123',
      dirty: false,
      final: true,
      status: 'blocked',
      environment: { os: 'darwin', node: 'v22' },
      checks: [
        {
          id: 'A1',
          title: 'Final feature status',
          status: 'pass',
          summary: 'ok',
          details: { n: 1 },
          evidence: [],
          durationMs: 10,
        },
        {
          id: 'K2',
          title: 'GitHub Actions',
          status: 'blocked',
          summary: 'pending push',
          details: null,
          evidence: [],
          durationMs: 1,
          request: 'Push this commit to origin',
        },
      ],
    };
    const md = renderAcceptanceMarkdown(report);
    assert.match(md, /Generated by port\/acceptance\/run\.mjs; do not edit\./);
    assert.match(md, /\| A1 \| Final feature status \| pass \| ok \|/);
    assert.match(md, /## Blocked requests/);
    assert.match(md, /Push this commit to origin/);
    assert.match(md, /"n": 1/);
  });
});
