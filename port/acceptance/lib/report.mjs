import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

/** @typedef {'pass' | 'fail' | 'blocked' | 'skipped'} CheckStatus */

/**
 * @typedef {object} CheckResult
 * @property {string} id
 * @property {string} title
 * @property {CheckStatus} status
 * @property {string} summary
 * @property {unknown} details
 * @property {string[]} evidence
 * @property {number} durationMs
 * @property {string} [request]
 */

/**
 * Compute report status from check results.
 * fail if any failed; else blocked if any blocked; else pass if K2 passed; else pass_local.
 * @param {CheckResult[]} checks
 * @returns {'pass_local' | 'pass' | 'fail' | 'blocked'}
 */
export function computeReportStatus(checks) {
  if (checks.some(c => c.status === 'fail')) return 'fail';
  if (checks.some(c => c.status === 'blocked')) return 'blocked';
  const k2 = checks.find(c => c.id === 'K2');
  if (k2 && k2.status === 'pass') return 'pass';
  return 'pass_local';
}

/**
 * @param {object} args
 * @param {CheckResult[]} args.checks
 * @param {boolean} args.final
 * @param {object} args.environment
 * @param {string} args.root
 * @returns {object}
 */
export function buildReport({ checks, final, environment, root }) {
  let gitSha = 'unknown';
  let dirty = true;
  try {
    gitSha = execFileSync('git', ['rev-parse', 'HEAD'], {
      cwd: root,
      encoding: 'utf8',
    }).trim();
    const status = execFileSync('git', ['status', '--porcelain'], {
      cwd: root,
      encoding: 'utf8',
    }).trim();
    dirty = status.length > 0;
  } catch {
    // keep defaults
  }
  return {
    schemaVersion: 1,
    generatedAt: new Date().toISOString(),
    gitSha,
    dirty,
    final: Boolean(final) && !dirty,
    environment,
    checks,
    status: computeReportStatus(checks),
  };
}

/**
 * Render docs/acceptance.md from a report object.
 * @param {object} report
 * @returns {string}
 */
export function renderAcceptanceMarkdown(report) {
  const lines = [
    'Generated by port/acceptance/run.mjs; do not edit.',
    '',
    `# Acceptance report`,
    '',
    `Status: **${report.status}**`,
    '',
    `| Field | Value |`,
    `|---|---|`,
    `| Generated | ${report.generatedAt} |`,
    `| Git SHA | \`${report.gitSha}\` |`,
    `| Dirty | ${report.dirty} |`,
    `| Final | ${report.final} |`,
    '',
    '## Checks',
    '',
    '| ID | Title | Status | Summary |',
    '|---|---|---|---|',
  ];
  for (const c of report.checks) {
    const summary = String(c.summary ?? '').replace(/\|/g, '\\|');
    lines.push(`| ${c.id} | ${c.title} | ${c.status} | ${summary} |`);
  }

  const blocked = report.checks.filter(c => c.status === 'blocked');
  if (blocked.length) {
    lines.push('', '## Blocked requests', '');
    for (const c of blocked) {
      lines.push(`### ${c.id}: ${c.title}`, '', c.request ?? c.summary, '');
    }
  }

  lines.push('', '## Environment', '');
  const env = report.environment ?? {};
  lines.push('| Key | Value |', '|---|---|');
  for (const [k, v] of Object.entries(env)) {
    lines.push(`| ${k} | ${String(v).replace(/\|/g, '\\|')} |`);
  }

  lines.push('', '## Check details', '');
  for (const c of report.checks) {
    lines.push(`### ${c.id}: ${c.title}`, '');
    lines.push(`- Status: ${c.status}`);
    lines.push(`- Summary: ${c.summary}`);
    lines.push(`- Duration: ${c.durationMs} ms`);
    if (c.request) lines.push(`- Request: ${c.request}`);
    if (c.evidence?.length) {
      lines.push(`- Evidence: ${c.evidence.join(', ')}`);
    }
    if (c.details != null) {
      lines.push('', '```json');
      lines.push(JSON.stringify(c.details, null, 2));
      lines.push('```', '');
    } else {
      lines.push('');
    }
  }
  return `${lines.join('\n')}\n`;
}

/**
 * @param {string} root
 * @param {object} report
 */
export function writeReportArtifacts(root, report) {
  const reportPath = join(root, 'port/state/acceptance/report.json');
  const summaryPath = join(root, 'port/state/acceptance/evidence/summary.json');
  const docsPath = join(root, 'docs/acceptance.md');
  mkdirSync(dirname(reportPath), { recursive: true });
  mkdirSync(dirname(summaryPath), { recursive: true });
  writeFileSync(reportPath, `${JSON.stringify(report, null, 2)}\n`);
  writeFileSync(
    summaryPath,
    `${JSON.stringify(
      {
        status: report.status,
        generatedAt: report.generatedAt,
        gitSha: report.gitSha,
        checks: report.checks.map(c => ({
          id: c.id,
          status: c.status,
          summary: c.summary,
        })),
      },
      null,
      2,
    )}\n`,
  );
  writeFileSync(docsPath, renderAcceptanceMarkdown(report));
}

/**
 * @param {Partial<CheckResult> & { id: string, title: string, status: CheckStatus }} partial
 * @returns {CheckResult}
 */
export function result(partial) {
  return {
    summary: '',
    details: null,
    evidence: [],
    durationMs: 0,
    ...partial,
  };
}
