import { readFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * @typedef {object} RouteSmokeEntry
 * @property {string} featureId
 * @property {string} route
 * @property {string} path
 * @property {'seededAlert'} [resolve] path is resolved at test time
 * @property {string} [expectText] text the page must show
 */

/**
 * Dynamic routes visited with a real document instead of a placeholder. The
 * spec resolves the path at test time from data global setup seeds; a second
 * entry visits a malformed id and expects the page's not-found state.
 */
const SEEDED_ROUTES = {
  '/alerts/[alertId]': {
    resolve: 'seededAlert',
    notFound: { path: '/alerts/smoke-alert', expectText: 'Alert not found' },
  },
};

/**
 * Fill dynamic Next.js segments from a values map.
 * @param {string} route e.g. /dashboards/[dashboardId]
 * @param {Record<string, string>} values
 * @returns {string}
 */
export function fillDynamicSegments(route, values) {
  return route.replace(/\[([^\]]+)\]/g, (_, name) => {
    if (values[name] == null || values[name] === '') {
      throw new Error(`Missing value for dynamic segment [${name}] in ${route}`);
    }
    return encodeURIComponent(values[name]);
  });
}

/**
 * Collect app_page routes for non-dropped features from features.json.
 * @param {string} root
 * @param {Record<string, string>} [segmentValues]
 * @returns {RouteSmokeEntry[]}
 */
export function collectRouteSmokeEntries(root, segmentValues = {}) {
  const features = JSON.parse(
    readFileSync(join(root, 'port/features.json'), 'utf8'),
  ).features;
  /** @type {RouteSmokeEntry[]} */
  const entries = [];
  for (const f of features) {
    if (f.status === 'dropped' || f.status === 'replaced') continue;
    for (const ep of f.entryPoints ?? []) {
      if (typeof ep !== 'string' || !ep.startsWith('app_page:')) continue;
      const route = ep.slice('app_page:'.length);
      const seeded = SEEDED_ROUTES[route];
      if (seeded && segmentValues.alertId == null) {
        entries.push({ featureId: f.id, route, path: route, resolve: seeded.resolve });
        entries.push({ featureId: f.id, route, ...seeded.notFound });
        continue;
      }
      let path;
      try {
        path = fillDynamicSegments(route, {
          savedSearchId: segmentValues.savedSearchId ?? 'smoke-saved-search',
          dashboardId: segmentValues.dashboardId ?? 'smoke-dashboard',
          alertId: segmentValues.alertId ?? 'smoke-alert',
          traceId: segmentValues.traceId ?? '00000000000000000000000000000001',
          sessionId: segmentValues.sessionId ?? 'smoke-session',
          ...segmentValues,
        });
      } catch (e) {
        // Skip routes we cannot fill.
        continue;
      }
      entries.push({ featureId: f.id, route, path });
    }
  }
  return entries;
}

/**
 * Generate the TypeScript source for route-smoke.spec.ts.
 * @param {string} root
 * @returns {string}
 */
export function generateRouteSmokeSpec(root) {
  const entries = collectRouteSmokeEntries(root);
  const paths = entries;
  const allowlist = JSON.parse(
    readFileSync(join(root, 'port/acceptance/console-allowlist.json'), 'utf8'),
  );
  const q = s => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  const routesLiteral = paths
    .map(p => {
      const extra = [
        p.resolve ? `\n    resolve: ${q(p.resolve)},` : '',
        p.expectText ? `\n    expectText: ${q(p.expectText)},` : '',
      ].join('');
      const title = p.expectText
        ? `${p.featureId} ${p.path} shows "${p.expectText}"`
        : `${p.featureId} ${p.route} loads`;
      return `  {\n    featureId: ${q(p.featureId)},\n    title: ${q(title)},\n    path: ${q(p.path)},\n    route: ${q(p.route)},${extra}\n  }`;
    })
    .join(',\n');
  const allowLiteral = allowlist
    .map(
      a =>
        `  {\n    pattern: ${q(a.pattern)},\n    reason: ${q(a.reason)},\n  }`,
    )
    .join(',\n');
  return `/**
 * Generated by port/acceptance/lib/routes.mjs — route smoke for acceptance A3.
 * Do not hand-edit path list; regenerate via the acceptance runner if needed.
 */
import type { Page } from '@playwright/test';

import { SEEDED_ERROR_ALERT } from '../global-setup-fullstack';
import { getApiUrl } from '../utils/api-helpers';
import { expect, test } from '../utils/base-test';

const CONSOLE_ALLOWLIST: { pattern: string; reason: string }[] = [
${allowLiteral},
];

type SmokeRoute = {
  featureId: string;
  title: string;
  path: string;
  route: string;
  resolve?: 'seededAlert';
  expectText?: string;
};

const ROUTES: SmokeRoute[] = [
${routesLiteral},
];

function consoleAllowed(text: string): boolean {
  return CONSOLE_ALLOWLIST.some(e => new RegExp(e.pattern, 'i').test(text));
}

/** The alert global setup seeds, so the detail page renders a real alert. */
async function seededAlertPath(page: Page): Promise<string> {
  const res = await page.request.get(\`\${getApiUrl()}/alerts\`);
  expect(res.ok(), 'GET /alerts').toBeTruthy();
  const alerts: { _id: string; savedSearch?: { name?: string } }[] = (
    await res.json()
  ).data;
  const alert = alerts.find(
    a => a.savedSearch?.name === SEEDED_ERROR_ALERT.savedSearchName,
  );
  expect(alert, 'seeded alert from global setup').toBeDefined();
  return \`/alerts/\${alert!._id}\`;
}

/** Routes that render a specific state (e.g. not found) must show its text. */
async function expectRouteText(page: Page, route: SmokeRoute): Promise<void> {
  if (route.expectText == null) return;
  await expect(page.getByText(route.expectText)).toBeVisible();
}

async function routePath(page: Page, route: SmokeRoute): Promise<string> {
  return route.resolve === 'seededAlert' ? seededAlertPath(page) : route.path;
}

test.describe('Route smoke', { tag: ['@acceptance', '@route-smoke'] }, () => {
  for (const route of ROUTES) {
    test(\`\${route.title}\`, async ({ page }) => {
      const pageErrors: string[] = [];
      const consoleErrors: string[] = [];
      const failedRequests: string[] = [];

      page.on('pageerror', err => pageErrors.push(String(err)));
      page.on('console', msg => {
        if (msg.type() === 'error') {
          const text = msg.text();
          if (!consoleAllowed(text)) consoleErrors.push(text);
        }
      });
      page.on('response', res => {
        const url = res.url();
        const origin = new URL(page.url()).origin;
        if (!url.startsWith(origin)) return;
        if (res.status() >= 500) {
          failedRequests.push(\`\${res.status()} \${url}\`);
        }
      });

      const path = await routePath(page, route);
      const res = await page.goto(path, { waitUntil: 'networkidle' });
      expect(
        res?.ok() || res?.status() === 200 || res?.status() === 304,
      ).toBeTruthy();
      await expectRouteText(page, route);
      expect(pageErrors, \`page errors on \${path}\`).toEqual([]);
      expect(consoleErrors, \`console errors on \${path}\`).toEqual([]);
      expect(failedRequests, \`failed requests on \${path}\`).toEqual([]);
    });
  }
});
`;
}
