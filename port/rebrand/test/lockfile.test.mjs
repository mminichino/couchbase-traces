// Cases 4-5: lockfile drift.
import assert from 'node:assert/strict';
import { describe, it } from 'node:test';

import { lockfileDrift, parseLockfile } from '../lib/lockfile.mjs';

const RENAMES = [
  { from: '@hyperdx/api', to: '@example-traces/api', dir: 'packages/api' },
  { from: '@hyperdx/common-utils', to: '@example-traces/common-utils', dir: 'packages/common-utils' },
];

const BASE = `# This file is generated by running "yarn install" inside your project.

__metadata:
  version: 8
  cacheKey: 10c0

"@hyperdx/api@workspace:packages/api":
  version: 0.0.0-use.local
  resolution: "@hyperdx/api@workspace:packages/api"
  dependencies:
    "@hyperdx/common-utils": "npm:^0.34.0"
    express: "npm:^4.0.0"
  languageName: unknown
  linkType: soft

"@hyperdx/common-utils@npm:^0.34.0, @hyperdx/common-utils@workspace:packages/common-utils":
  version: 0.0.0-use.local
  resolution: "@hyperdx/common-utils@workspace:packages/common-utils"
  languageName: unknown
  linkType: soft

"express@npm:^4.0.0":
  version: 4.19.2
  resolution: "express@npm:4.19.2"
  dependencies:
    accepts: "npm:~1.3.8"
  checksum: 10c0/abc
  languageName: node
  linkType: hard

"accepts@npm:~1.3.8":
  version: 1.3.8
  resolution: "accepts@npm:1.3.8"
  checksum: 10c0/def
  languageName: node
  linkType: hard
`;

/** Head as Yarn would write it after the rename. */
const HEAD = `# This file is generated by running "yarn install" inside your project.

__metadata:
  version: 8
  cacheKey: 10c0

"@example-traces/api@workspace:packages/api":
  version: 0.0.0-use.local
  resolution: "@example-traces/api@workspace:packages/api"
  dependencies:
    "@example-traces/common-utils": "workspace:*"
    express: "npm:^4.0.0"
  languageName: unknown
  linkType: soft

"@example-traces/common-utils@workspace:*, @example-traces/common-utils@workspace:packages/common-utils":
  version: 0.0.0-use.local
  resolution: "@example-traces/common-utils@workspace:packages/common-utils"
  languageName: unknown
  linkType: soft

"express@npm:^4.0.0":
  version: 4.19.2
  resolution: "express@npm:4.19.2"
  dependencies:
    accepts: "npm:~1.3.8"
  checksum: 10c0/abc
  languageName: node
  linkType: hard

"accepts@npm:~1.3.8":
  version: 1.3.8
  resolution: "accepts@npm:1.3.8"
  checksum: 10c0/def
  languageName: node
  linkType: hard
`;

describe('lockfile', () => {
  it('parses entries and ignores __metadata', () => {
    const m = parseLockfile(BASE);
    assert.equal(m.size, 4);
    assert.equal(m.get('express@npm:^4.0.0')?.checksum, '10c0/abc');
    assert.ok(![...m.keys()].includes('__metadata'));
  });

  it('4. a workspace rename alone has no problems', () => {
    assert.deepEqual(lockfileDrift(BASE, HEAD, RENAMES), []);
  });

  it('5. a changed external checksum is reported', () => {
    const problems = lockfileDrift(BASE, HEAD.replace('10c0/abc', '10c0/zzz'), RENAMES);
    assert.ok(problems.length >= 2, problems.join('\n'));
    assert.ok(problems.some(p => p.includes('express@npm:4.19.2')));
  });

  it('reports a missing workspace entry and a leftover old name', () => {
    const missing = lockfileDrift(BASE, HEAD.replaceAll('"@example-traces/api@workspace:packages/api"', '"@example-traces/zzz@workspace:packages/api"'), RENAMES);
    assert.ok(missing.some(p => p.includes('exactly one workspace entry')));
    const stale = lockfileDrift(BASE, HEAD + '\n"foo@npm:1":\n  version: 1\n  resolution: "foo@npm:1"\n  dependencies:\n    "@hyperdx/api": "npm:1"\n', RENAMES);
    assert.ok(stale.some(p => p.includes('old workspace name') || p.includes('external entry')));
  });
});
